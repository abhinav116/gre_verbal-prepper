export async function GET() {
  const results: Array<{ word: string; status: string }> = []

  for (const entry of SEED_DATA) {
    const { data: existing } = await supabaseAdmin
      .from('vocab_words')
      .select('id')
      .eq('word', entry.word)
      .single()

    if (existing) {
      const { error } = await supabaseAdmin
        .from('vocab_words')
        .update({
          reference_type: entry.reference_type,
          reference_name: entry.reference_name,
          reference_context: entry.reference_context,
        })
        .eq('word', entry.word)
      results.push({ word: entry.word, status: error ? `error: ${error.message}` : 'updated' })
      continue
    }

    const { error } = await supabaseAdmin.from('vocab_words').insert(entry)
    results.push({ word: entry.word, status: error ? `error: ${error.message}` : 'created' })
  }

  return NextResponse.json({ done: true, results })
}
